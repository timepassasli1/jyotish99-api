def search_places(q: str, limit: int = 12) -> List[str]:
    query = (q or "").strip().lower()
    if not query:
        # Popular defaults (like Places "featured")
        return [name for name, _ in _RAW[:12]]

    scored = []
    for name, aliases in _RAW:
        hay = f"{name.lower()} {aliases.lower()}"
        if query in hay:
            # Prefer starts-with / earlier match
            pos = hay.find(query)
            scored.append((pos, len(name), name))
    scored.sort()
    # unique preserve order
    seen = set()
    out: List[str] = []
    for _, _, name in scored:
        if name in seen:
            continue
        seen.add(name)
        out.append(name)
        if len(out) >= limit:
            break

    # Always allow free-text custom place if nothing / few matches
    if query and len(out) < 3:
        custom = q.strip().title()
        if custom and custom not in out:
            out.append(f"{custom}")
    return out
